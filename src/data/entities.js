const NUMERIC_HINT_KEYS = ["size", "age", "joinYear"];

export function formatAttributeValue(key, value) {
  if (key === "size") {
    return `${value} cm`;
  }

  // if (key === "salary") {
  //   return value.replace(/\+/g, "€");
  // }

  return String(value);
}

export function compareAttribute(key, guessVal, targetVal) {
  if (NUMERIC_HINT_KEYS.includes(key)) {
    if (guessVal === targetVal) {
      return { status: "correct", hint: null };
    }

    return { status: "wrong", hint: guessVal > targetVal ? "↓" : "↑" };
  }

  return { status: guessVal === targetVal ? "correct" : "wrong", hint: null };
}

export function getDailyEntity() {
  const today = new Date();
  const dayOfYear = Math.floor(
    (today - new Date(today.getFullYear(), 0, 0)) / (1000 * 60 * 60 * 24)
  );
  const entityIndex = dayOfYear % (ENTITIES.length - 2);
  return ENTITIES[entityIndex];
}
